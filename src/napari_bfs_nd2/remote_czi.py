"""High-performance CZI reader for local, HTTP(S), and S3 paths.

Uses pylibczirw directly (not through BioImage) for frame-level parallelism,
matching the RemoteND2Reader pattern. Each Z-slice is read independently via
GetSingleChannelScalingTileAccessorData, enabling ThreadPoolExecutor-based
parallel reads that saturate network and disk I/O.

This module is adapted from BFS2's CZI implementation and is distributed under
the BSD 3-Clause license included with this package. S3 objects are presented
to libCZI as cached, short-lived HTTPS URLs generated by s3fs.
"""

from __future__ import annotations

import logging
import threading
import time
from concurrent.futures import ThreadPoolExecutor
from xml.etree import ElementTree

import _pylibCZIrw
import numpy as np

from .remote_nd2 import _s3_storage_options

logger = logging.getLogger(__name__)

# Module-level metadata cache (keyed by file path)
_czi_metadata_cache: dict[str, dict] = {}
_cache_lock = threading.Lock()

# Total subblock-cache budget (MB) across all per-thread reader instances of
# one CZIReader. Parallel reads previously opened max_workers+1 readers, each
# holding a ~cache_size_mb subblock cache (code-review finding I10). Workers
# are capped so pooled readers never hold more than this budget in caches;
# with the default cache_size_mb=64 this preserves the default 8 workers.
_CZI_READER_CACHE_BUDGET_MB = 512

# Concurrency for a single *remote* z-stack read, measured rather than derived.
#
# Local caps workers by memory (_CZI_READER_CACHE_BUDGET_MB // cache_size_mb),
# which is the right bound when the reader is CPU- and RAM-bound. Remote is
# latency-bound — threads sit in socket waits — so that heuristic caps the wrong
# thing: at the 64 MB default it allows only 8 workers no matter how much
# concurrency the link would reward.
#
# Measured on an S3 CZI with scripts/bench_czi_reader.py (666 MB z-stack,
# best of 3, one stack at a time):
#
#      1 thread    49.56s    13 MB/s
#      4 threads   16.09s    41 MB/s
#      8 threads    6.83s    98 MB/s
#     16 threads    4.32s   154 MB/s   <- optimum
#     32 threads    6.87s    97 MB/s   <- oversubscribed, back to 8-thread speed
_REMOTE_MAX_PARALLEL_WORKERS = 16

# Default z-stack read width when a caller does not choose one. Remote takes the
# measured optimum above; local keeps the historical 8, which nothing measured
# argues against. Callers that know their own shape — extraction passes
# nd2_reader_threads, sized against a whole-pipeline thread budget — still win,
# since these are only defaults.
_REMOTE_DEFAULT_WORKERS = _REMOTE_MAX_PARALLEL_WORKERS
_LOCAL_DEFAULT_WORKERS = 8

# Idle *remote* readers, parked by (path, cache_size_mb) so they outlive the
# CZIReader that opened them.
#
# Opening a reader over curl re-downloads and re-parses the whole subblock
# directory, which on a real time-lapse is enormous (81T x 24S x 40Z x 2C =
# 155,520 subblocks measured ~5.5s per open, with the metadata cache already
# warm). Every call site uses `with CZIReader(path) as czi:`, and the
# per-instance free-list dies with it, so each parallel read re-opened one
# reader per worker and paid that parse N times over. Measured on an S3 file:
# a cold read took 31.0s and the next three reads — different timepoints, so
# not a subblock-cache effect — took 7.0-8.6s once readers were reused.
#
# Local files are deliberately NOT pooled: opening them is cheap, and holding
# handles open would block deleting or moving the file on Windows.
_remote_reader_pool: dict[tuple[str, int], list[_pylibCZIrw.czi_reader]] = {}
_remote_pool_lock = threading.Lock()

# Bound on distinct (path, cache_size_mb) keys held open. Presigned URLs carry
# a signature in the query string, so re-signing the same object mints a new
# key; without a bound those would accumulate. Oldest key is evicted first.
_REMOTE_POOL_MAX_KEYS = 4

# Memory ceiling (MB) for parked readers of one key, which sets how many are
# kept: 1024 // 64 = 16 at the default cache size, 128 at cache_size_mb=8.
#
# Sized as memory rather than reusing _max_parallel_workers, which bounds
# *concurrent* workers within one read. Extraction drives far more readers than
# that: raw_extraction runs `extraction_read_workers` timepoints at once, each
# opening its own CZIReader with `nd2_reader_threads` Z-threads, targeting ~96
# total. Capping the pool at the worker number (512 // 64 = 8) meant those extra
# readers were opened and closed on every cycle, so extraction kept paying the
# subblock-directory parse the pool exists to eliminate. Parked readers are
# idle, so the only thing worth bounding is the memory their caches hold.
_REMOTE_POOL_MAX_MB = 1024

# libCZI stream class names, as passed to the czi_reader(class, path, cache)
# overload. These are the values of pylibCZIrw.czi.ReaderFileInputTypes; they
# are hardcoded rather than imported because this module deliberately uses the
# `_pylibCZIrw` extension directly and does not import the Python wrapper.
_STANDARD_STREAM = "standard"
_CURL_STREAM = "curl"

# libCZI supports local paths and HTTP(S), but not the s3:// scheme. s3fs can
# generate a signed HTTPS URL that retains byte-range support. Cache it briefly
# so every Dask plane does not create a new URL (and a new expensive libCZI
# subblock-directory cache key).
_S3_URL_EXPIRATION_SECONDS = 3600
_S3_URL_REFRESH_MARGIN_SECONDS = 300
_s3_url_cache: dict[str, tuple[str, float]] = {}
_s3_url_lock = threading.Lock()

# PixelType -> numpy dtype mapping
_PIXEL_TYPE_TO_DTYPE: dict[_pylibCZIrw.PixelType, np.dtype] = {
    _pylibCZIrw.PixelType.Gray8: np.dtype("uint8"),
    _pylibCZIrw.PixelType.Gray16: np.dtype("uint16"),
    _pylibCZIrw.PixelType.Gray32: np.dtype("uint32"),
    _pylibCZIrw.PixelType.Gray32Float: np.dtype("float32"),
}

# Reusable no-tint color (all white = no color change)
_NO_TINT = _pylibCZIrw.RgbFloatColor()
_NO_TINT.r = 1.0
_NO_TINT.g = 1.0
_NO_TINT.b = 1.0


def _make_roi(x: int, y: int, w: int, h: int) -> _pylibCZIrw.IntRect:
    roi = _pylibCZIrw.IntRect()
    roi.x = x
    roi.y = y
    roi.w = w
    roi.h = h
    return roi


def _to_intrect(obj: object) -> _pylibCZIrw.IntRect:
    """Extract IntRect from an object that may be IntRect or BoundingBoxes."""
    if isinstance(obj, _pylibCZIrw.IntRect):
        return obj
    # BoundingBoxes wraps IntRect in .boundingBoxLayer0 or .boundingBox
    if hasattr(obj, "boundingBoxLayer0"):
        return obj.boundingBoxLayer0
    if hasattr(obj, "boundingBox"):
        return obj.boundingBox
    raise TypeError(f"Cannot extract IntRect from {type(obj)}: {obj}")


def _is_remote_path(path: str) -> bool:
    """True for URLs libCZI streams via curl (the only remote form it handles)."""
    return str(path).startswith(("http://", "https://"))


def _resolve_czi_path(path: str) -> str:
    """Translate an S3 URI into a cached HTTPS URL understood by libCZI."""
    path = str(path)
    if not path.startswith("s3://"):
        return path

    now = time.monotonic()
    with _s3_url_lock:
        cached = _s3_url_cache.get(path)
        if cached is not None and now < cached[1]:
            return cached[0]

        import s3fs

        fs = s3fs.S3FileSystem(**_s3_storage_options())
        url = fs.sign(path, expiration=_S3_URL_EXPIRATION_SECONDS)
        refresh_at = now + _S3_URL_EXPIRATION_SECONDS - _S3_URL_REFRESH_MARGIN_SECONDS
        _s3_url_cache[path] = (url, refresh_at)
        return url


def clear_czi_reader_pool() -> None:
    """Close every parked remote reader and empty the pool."""
    with _remote_pool_lock:
        parked = [r for readers in _remote_reader_pool.values() for r in readers]
        _remote_reader_pool.clear()
    for reader in parked:
        try:
            reader.close()
        except Exception:  # noqa: BLE001 - a failed close must not mask the caller's work
            pass


def clear_czi_metadata_cache() -> None:
    with _cache_lock:
        _czi_metadata_cache.clear()
    # Parked readers hold the metadata this cache describes, so a caller asking
    # for a clean slate must not be handed a reader opened against the old one.
    clear_czi_reader_pool()


def _parse_czi_pixel_sizes(xml_str: str) -> tuple[float | None, float | None, float | None]:
    """Parse (x, y, z) physical pixel sizes in micrometers from CZI XML metadata.

    Zeiss CZI files can encode anisotropic XY sampling, so X and Y are parsed
    independently. If the Y distance is absent, it falls back to X so callers
    still receive a usable isotropic-XY value. Returns ``None`` for any axis
    that cannot be parsed.
    """
    pixel_x: float | None = None
    pixel_y: float | None = None
    pixel_z: float | None = None

    root = ElementTree.fromstring(xml_str)
    ns = {"m": "http://www.zeiss.com/2019/01/01"}
    # Try standard Zeiss path
    scaling = root.find(".//m:Scaling/m:Items", ns)
    if scaling is None:
        # Fallback: try without namespace
        scaling = root.find(".//Scaling/Items")
    if scaling is not None:
        for dist in scaling.findall("m:Distance", ns) or scaling.findall("Distance"):
            axis_id = dist.get("Id", "")
            val_el = dist.find("m:Value", ns)
            if val_el is None:
                val_el = dist.find("Value")
            if val_el is not None and val_el.text:
                val_um = float(val_el.text) * 1e6  # meters -> micrometers
                if axis_id == "X":
                    pixel_x = val_um
                elif axis_id == "Y":
                    pixel_y = val_um
                elif axis_id == "Z":
                    pixel_z = val_um

    # If Y was not present in the metadata, fall back to X so callers still
    # get a usable isotropic-XY value rather than None.
    if pixel_y is None:
        pixel_y = pixel_x

    return pixel_x, pixel_y, pixel_z


class CZIReader:
    """High-performance CZI reader with parallel Z-slice reading.

    Opens a CZI file using pylibczirw directly and provides parallel
    Z-stack reading via ThreadPoolExecutor. Each worker thread opens
    its own reader instance for thread safety.

    Parameters
    ----------
    path : str
        Path to the CZI file (local path or URL supported by pylibczirw).
    cache_size_mb : int
        Max subblock cache size per reader instance in MB.
    """

    def __init__(self, path: str, cache_size_mb: int = 64):
        self.source_path = str(path)
        self.path = _resolve_czi_path(self.source_path)
        self._cache_size_mb = cache_size_mb
        self._is_remote = _is_remote_path(path)

        # Free-list of per-thread readers reused across read_zstack* calls
        # instead of opening (and re-opening) one reader per worker per call,
        # each with its own ~cache_size_mb subblock cache (I10).
        self._pool_readers: list[_pylibCZIrw.czi_reader] = []
        self._pool_lock = threading.Lock()

        # Bound before the open below so __del__ -> close() has something to
        # read if that open raises — a live possibility for remote paths (bad
        # URL, expired presigned signature), where the AttributeError would
        # otherwise be raised inside __del__ and mask the real failure.
        self._reader: _pylibCZIrw.czi_reader | None = None

        # Primary reader for metadata. Goes through the pool so a remote reopen
        # reuses a parked reader instead of re-parsing the subblock directory.
        self._reader = self._acquire_pooled_reader()

        # Parse metadata (cached at module level)
        self._load_metadata()

    def _open_reader(self) -> _pylibCZIrw.czi_reader:
        cache_opts = _pylibCZIrw.SubBlockCacheOptions()
        cache_opts.cacheType = _pylibCZIrw.CacheType.Standard
        cache_opts.pruneOptions.maxMemoryUsage = self._cache_size_mb * 1024 * 1024
        cache_opts.pruneOptions.maxSubBlockCount = 500
        # libCZI needs its stream class named explicitly. The (path, cache)
        # overload is the local-file reader and fails on a URL with
        # `Error opening the file "<url>"` — it never attempts a fetch. Select
        # the curl stream for http(s) so remote reads work without bioio-czi.
        #
        # cacheOnlyCompressed stays True for remote as well as local. 0f9f28f set
        # it False for remote, copying pylibCZIrw's own CziReader on the theory
        # that the connection dominates so uncompressed blocks are worth caching.
        # Measured, that is backwards for a first read: best-of-3 on a warm page
        # cache, w=4 took 0.063s with False against 0.037s with True, and it
        # scaled worst of the three cache configurations (2.67x at w=8 vs 4.20x).
        # Caching uncompressed data only pays when the same subblocks are read
        # again, which extraction — the wall-time case — never does.
        cache_opts.cacheOnlyCompressed = True
        stream_class = _CURL_STREAM if self._is_remote else _STANDARD_STREAM
        try:
            return _pylibCZIrw.czi_reader(stream_class, self.path, cache_opts)
        except Exception as exc:
            if self.source_path.startswith("s3://"):
                raise RuntimeError(
                    f"Could not open CZI from {self.source_path}. Check S3 access and whether the object exists."
                ) from None
            raise exc

    def _resolve_workers(self, max_workers: int | None) -> int:
        """Pick a read width when the caller did not: measured optimum if remote."""
        if max_workers is not None:
            return max_workers
        return _REMOTE_DEFAULT_WORKERS if self._is_remote else _LOCAL_DEFAULT_WORKERS

    def _max_parallel_workers(self, max_workers: int) -> int:
        """Cap workers: measured concurrency optimum if remote, cache budget if local.

        Local is bounded by the memory its pooled subblock caches hold (I10).
        Remote is latency-bound, so it is bounded by the point past which more
        in-flight requests stop helping — 16, measured; 32 was no better than 8.
        """
        if self._is_remote:
            return max(1, min(max_workers, _REMOTE_MAX_PARALLEL_WORKERS))
        budget_workers = max(1, _CZI_READER_CACHE_BUDGET_MB // max(1, self._cache_size_mb))
        return max(1, min(max_workers, budget_workers))

    def _acquire_pooled_reader(self) -> _pylibCZIrw.czi_reader:
        """Take a reader from the free-lists, opening a new one only when empty.

        Checks this instance's list first, then the module-level pool of parked
        remote readers, so a remote read reuses readers opened by an earlier
        ``with CZIReader(...)`` block instead of re-parsing the subblock
        directory once per worker.
        """
        with self._pool_lock:
            if self._pool_readers:
                return self._pool_readers.pop()
        if self._is_remote:
            key = (self.path, self._cache_size_mb)
            with _remote_pool_lock:
                parked = _remote_reader_pool.get(key)
                if parked:
                    return parked.pop()
        return self._open_reader()

    def _park_remote_readers(self, readers: list[_pylibCZIrw.czi_reader]) -> None:
        """Hand still-open remote readers to the module pool, closing the excess.

        Bounded twice over: by ``_REMOTE_POOL_MAX_MB`` of cache memory per key,
        and by ``_REMOTE_POOL_MAX_KEYS`` keys, evicting the oldest key first.
        """
        key = (self.path, self._cache_size_mb)
        limit = max(1, _REMOTE_POOL_MAX_MB // max(1, self._cache_size_mb))
        surplus: list[_pylibCZIrw.czi_reader] = []
        with _remote_pool_lock:
            parked = _remote_reader_pool.setdefault(key, [])
            for reader in readers:
                if len(parked) < limit:
                    parked.append(reader)
                else:
                    surplus.append(reader)
            # Re-insert so this key becomes the most recently used. Plain dicts
            # preserve insertion order, so the oldest key is simply the first.
            _remote_reader_pool[key] = _remote_reader_pool.pop(key)
            while len(_remote_reader_pool) > _REMOTE_POOL_MAX_KEYS:
                oldest = next(iter(_remote_reader_pool))
                surplus.extend(_remote_reader_pool.pop(oldest))
        for reader in surplus:
            try:
                reader.close()
            except Exception:  # noqa: BLE001 - a failed close must not mask the caller's work
                pass

    def _release_pooled_reader(self, reader: _pylibCZIrw.czi_reader) -> None:
        """Return a reader to the free-list for reuse by later reads."""
        with self._pool_lock:
            self._pool_readers.append(reader)

    def _load_metadata(self) -> None:
        with _cache_lock:
            cached = _czi_metadata_cache.get(self.source_path)

        if cached:
            self._apply_cached_metadata(cached)
            logger.info(f"[CZI_CACHE HIT] Using cached metadata for {self.source_path}")
            return

        r = self._reader  # Always set when called from __init__
        assert r is not None
        DI = _pylibCZIrw.DimensionIndex

        self.num_scenes = max(1, r.GetDimensionSize(DI.S))
        self.num_channels = max(1, r.GetDimensionSize(DI.C))
        self.num_timepoints = max(1, r.GetDimensionSize(DI.T))
        self.num_z = max(1, r.GetDimensionSize(DI.Z))

        # Get pixel type and dtype
        self.pixel_type = r.GetChannelPixelType(0)
        self.dtype = _PIXEL_TYPE_TO_DTYPE.get(self.pixel_type, np.dtype("uint16"))

        # Get image dimensions from subblock statistics
        stats = r.GetSubBlockStats()
        bbox = _to_intrect(stats.boundingBoxLayer0Only)
        self.width = bbox.w
        self.height = bbox.h
        self._bbox_x = bbox.x
        self._bbox_y = bbox.y

        # Per-scene bounding boxes (for multi-position files)
        self._scene_bboxes: dict[int, tuple[int, int, int, int]] = {}
        if stats.sceneBoundingBoxes:
            for scene_idx, sb_raw in stats.sceneBoundingBoxes.items():
                sb = _to_intrect(sb_raw)
                self._scene_bboxes[scene_idx] = (sb.x, sb.y, sb.w, sb.h)

        # CZI scene indices are not always 0-based: split acquisitions can start
        # at S=65. Keep the file's actual indices so the logical 0-based `s`
        # arguments callers pass can be translated through them.
        #
        # sceneBoundingBoxes only describes scenes that actually have subblocks,
        # so it can be sparser than the declared S size (sparse / unacquired
        # scenes). Deriving num_scenes from it would then hide declared scenes
        # from callers, so the file's real indices are adopted only when both
        # sources agree on the count; otherwise the declared count wins and
        # indexing stays 0-based, as it was before scene mapping existed.
        bbox_indices = sorted(self._scene_bboxes)
        if len(bbox_indices) == self.num_scenes:
            self.scene_indices = bbox_indices
        else:
            if bbox_indices:
                logger.debug(
                    f"[CZI] {self.source_path}: {len(bbox_indices)} scene bounding box(es) for "
                    f"{self.num_scenes} declared scene(s); keeping 0-based scene indices"
                )
            self.scene_indices = list(range(self.num_scenes))

        # Parse XML metadata for pixel sizes.
        # pixel_size_xy holds the X sampling (kept for backward compatibility);
        # pixel_size_y is parsed independently because Zeiss CZI files can have
        # anisotropic XY sampling — reusing X for Y silently corrupts it.
        self.pixel_size_xy = None
        self.pixel_size_y = None
        self.pixel_size_z = None
        try:
            xml_str = r.GetXmlMetadata()
            self.pixel_size_xy, self.pixel_size_y, self.pixel_size_z = _parse_czi_pixel_sizes(xml_str)
        except Exception as e:
            logger.debug(f"Could not parse CZI XML metadata for pixel sizes: {e}")

        # Cache metadata
        meta = {
            "num_scenes": self.num_scenes,
            "num_channels": self.num_channels,
            "num_timepoints": self.num_timepoints,
            "num_z": self.num_z,
            "pixel_type": self.pixel_type,
            "dtype": self.dtype,
            "width": self.width,
            "height": self.height,
            "bbox_x": self._bbox_x,
            "bbox_y": self._bbox_y,
            "scene_bboxes": self._scene_bboxes,
            "scene_indices": self.scene_indices,
            "pixel_size_xy": self.pixel_size_xy,
            "pixel_size_y": self.pixel_size_y,
            "pixel_size_z": self.pixel_size_z,
        }
        with _cache_lock:
            _czi_metadata_cache[self.source_path] = meta

        logger.info(
            f"[CZI] Opened {self.source_path}: {self.num_scenes}S, {self.num_channels}C, "
            f"{self.num_timepoints}T, {self.num_z}Z, {self.height}x{self.width}, "
            f"dtype={self.dtype}, pixel_x={self.pixel_size_xy}, pixel_y={self.pixel_size_y}, "
            f"pixel_z={self.pixel_size_z}"
        )

    def _apply_cached_metadata(self, cached: dict) -> None:
        self.num_scenes = cached["num_scenes"]
        self.num_channels = cached["num_channels"]
        self.num_timepoints = cached["num_timepoints"]
        self.num_z = cached["num_z"]
        self.pixel_type = cached["pixel_type"]
        self.dtype = cached["dtype"]
        self.width = cached["width"]
        self.height = cached["height"]
        self._bbox_x = cached["bbox_x"]
        self._bbox_y = cached["bbox_y"]
        self._scene_bboxes = cached["scene_bboxes"]
        self.scene_indices = cached["scene_indices"]
        self.pixel_size_xy = cached["pixel_size_xy"]
        self.pixel_size_y = cached.get("pixel_size_y", cached["pixel_size_xy"])
        self.pixel_size_z = cached["pixel_size_z"]

    def _czi_scene(self, s: int) -> int:
        """Translate a logical 0-based scene index to the file's CZI scene index."""
        if 0 <= s < len(self.scene_indices):
            return self.scene_indices[s]
        return s

    def _get_scene_roi(self, s: int, crop: tuple[int, int, int, int, int, int] | None = None) -> _pylibCZIrw.IntRect:
        """Get the ROI for a scene, optionally with crop applied.

        Parameters
        ----------
        s : int
            Scene index.
        crop : tuple, optional
            (z_start, z_end, y_start, y_end, x_start, x_end) - Y/X applied to ROI.

        Returns
        -------
        IntRect
            ROI for the GetSingleChannelScalingTileAccessorData call.
        """
        czi_s = self._czi_scene(s)
        if czi_s in self._scene_bboxes:
            bx, by, bw, bh = self._scene_bboxes[czi_s]
        else:
            bx, by, bw, bh = self._bbox_x, self._bbox_y, self.width, self.height

        if crop is not None:
            _, _, y_start, y_end, x_start, x_end = crop
            return _make_roi(bx + x_start, by + y_start, x_end - x_start, y_end - y_start)
        return _make_roi(bx, by, bw, bh)

    def _read_frame(
        self,
        reader: _pylibCZIrw.czi_reader,
        t: int,
        c: int,
        z: int,
        s: int,
        roi: _pylibCZIrw.IntRect,
    ) -> np.ndarray:
        """Read a single 2D frame (one Z-slice) using an existing reader."""
        # plane_spec: space-separated "C0 Z5 T10" (pylibczirw convention)
        # scene_spec: just the number as string, or "" if single-scene
        plane_spec = f"C{c} Z{z} T{t}"
        scene_spec = str(self._czi_scene(s)) if self.num_scenes > 1 else ""

        pimage = reader.GetSingleChannelScalingTileAccessorData(
            self.pixel_type,
            roi,
            _NO_TINT,
            1.0,
            plane_spec,
            scene_spec,
        )
        # pylibczirw PImage exposes a non-C-contiguous memoryview that
        # np.frombuffer rejects.  np.array() handles any array/buffer protocol
        # object and always produces an owned, contiguous copy.
        frame = np.array(pimage, dtype=self.dtype, copy=True).reshape(roi.h, roi.w)
        return frame

    def read_frame(self, t: int, c: int, z: int, s: int = 0) -> np.ndarray:
        """Read a single 2D frame (one Z-slice) as (Y, X)."""
        return self._read_frame(self._reader, t, c, z, s, self._get_scene_roi(s))

    def scene_shape(self, s: int = 0) -> tuple[int, int]:
        """Return the (height, width) of a scene's bounding box in pixels."""
        roi = self._get_scene_roi(s)
        return roi.h, roi.w

    def get_xml_metadata(self) -> str:
        """Return the raw CZI XML metadata document."""
        return self._reader.GetXmlMetadata()

    def read_zstack(
        self,
        t: int,
        c: int,
        s: int = 0,
        max_workers: int | None = None,
        crop: tuple[int, int, int, int, int, int] | None = None,
    ) -> np.ndarray:
        """Read a full Z-stack with parallel Z-slice reading.

        Parameters
        ----------
        t : int
            Timepoint index (0-based).
        c : int
            Channel index (0-based).
        s : int
            Scene index (0-based).
        max_workers : int, optional
            Number of threads for parallel Z-slice reads. When ``None``,
            resolves to the remote or local default for this path.
        crop : tuple, optional
            (z_start, z_end, y_start, y_end, x_start, x_end) for 3D crop.
            Z range selects which slices to read; Y/X crop is applied via ROI.

        Returns
        -------
        np.ndarray
            Z-stack with shape (Z, Y, X).
        """
        max_workers = self._resolve_workers(max_workers)
        roi = self._get_scene_roi(s, crop)
        out_h, out_w = roi.h, roi.w

        # Determine Z range
        if crop is not None:
            z_start, z_end = crop[0], crop[1]
        else:
            z_start, z_end = 0, self.num_z

        num_z_out = z_end - z_start
        z_indices = list(range(z_start, z_end))

        # Pre-allocate output array
        output = np.empty((num_z_out, out_h, out_w), dtype=self.dtype)

        if max_workers <= 1 or num_z_out <= 1:
            # Sequential path
            for i, z in enumerate(z_indices):
                output[i] = self._read_frame(self._reader, t, c, z, s, roi)
        else:
            # Parallel path: workers borrow readers from the instance pool so
            # at most `workers` extra readers (and subblock caches) ever exist
            # and they are reused across calls instead of reopened (I10).
            def _read_z_slice(args: tuple[int, int]) -> None:
                out_idx, z = args
                reader = self._acquire_pooled_reader()
                try:
                    output[out_idx] = self._read_frame(reader, t, c, z, s, roi)
                finally:
                    self._release_pooled_reader(reader)

            workers = min(self._max_parallel_workers(max_workers), num_z_out)
            with ThreadPoolExecutor(max_workers=workers, thread_name_prefix="czi_z") as pool:
                list(pool.map(_read_z_slice, enumerate(z_indices)))

        return output

    def read_zstack_multichannel(
        self,
        t: int,
        channels: list[int],
        s: int = 0,
        max_workers: int | None = None,
        crop: tuple[int, int, int, int, int, int] | None = None,
    ) -> dict[int, np.ndarray]:
        """Read Z-stacks for multiple channels in parallel.

        Unlike ND2's interleaved format, CZI stores channels separately so
        there's no single-pass multi-channel optimization. But we can still
        read all (channel, z) combinations in parallel for throughput.

        Parameters
        ----------
        t : int
            Timepoint index (0-based).
        channels : list of int
            Channel indices (0-based) to read.
        s : int
            Scene index (0-based).
        max_workers : int, optional
            Number of threads for parallel (channel, Z) reads. When ``None``,
            resolves to the remote or local default for this path.
        crop : tuple, optional
            (z_start, z_end, y_start, y_end, x_start, x_end) for 3D crop.
            Z range selects which slices to read; Y/X crop is applied via ROI.

        Returns
        -------
        dict[int, np.ndarray]
            Mapping of channel index to Z-stack (Z, Y, X).
        """
        max_workers = self._resolve_workers(max_workers)
        roi = self._get_scene_roi(s, crop)
        out_h, out_w = roi.h, roi.w

        if crop is not None:
            z_start, z_end = crop[0], crop[1]
        else:
            z_start, z_end = 0, self.num_z

        num_z_out = z_end - z_start
        z_indices = list(range(z_start, z_end))

        # Pre-allocate output arrays for all channels
        outputs: dict[int, np.ndarray] = {}
        for ch in channels:
            outputs[ch] = np.empty((num_z_out, out_h, out_w), dtype=self.dtype)

        # Build all (channel, z_index, z_slice) tasks
        tasks: list[tuple[int, int, int]] = []
        for ch in channels:
            for i, z in enumerate(z_indices):
                tasks.append((ch, i, z))

        if max_workers <= 1 or len(tasks) <= 1:
            for ch, out_idx, z in tasks:
                outputs[ch][out_idx] = self._read_frame(self._reader, t, ch, z, s, roi)
        else:
            # Workers borrow readers from the shared instance pool (I10).
            def _read_slice(args: tuple[int, int, int]) -> None:
                ch, out_idx, z = args
                reader = self._acquire_pooled_reader()
                try:
                    outputs[ch][out_idx] = self._read_frame(reader, t, ch, z, s, roi)
                finally:
                    self._release_pooled_reader(reader)

            workers = min(self._max_parallel_workers(max_workers), len(tasks))
            with ThreadPoolExecutor(max_workers=workers, thread_name_prefix="czi_mc") as pool:
                list(pool.map(_read_slice, tasks))

        return outputs

    def close(self) -> None:
        # Reclaim pooled per-thread readers plus the primary (I10).
        with self._pool_lock:
            pooled, self._pool_readers = self._pool_readers, []
        if self._reader is not None:
            pooled.append(self._reader)
            self._reader = None

        # Remote readers are expensive to reopen (subblock-directory parse over
        # curl), so park them for the next CZIReader on this URL instead of
        # closing. Local readers are closed as before: reopening them is cheap,
        # and a held handle blocks deleting or moving the file on Windows.
        if self._is_remote:
            self._park_remote_readers(pooled)
            return

        for _r in pooled:
            try:
                _r.close()
            except Exception:
                pass

    def __enter__(self):
        return self

    def __exit__(self, *_args):
        self.close()

    def __del__(self):
        self.close()
